#!/usr/bin/env python3
"""
Generate adapter files for other agentic frameworks from the canonical
`skills/` and `agents/` sources.

Sources (canonical):
    skills/<name>/SKILL.md     -> user-invocable prompt / procedure
    agents/<name>.md           -> sub-agent definition

Targets (generated — safe to delete, regenerate from source):
    .cursor/rules/<name>.mdc                      (Cursor)
    .github/prompts/<name>.prompt.md              (Copilot, from skills)
    .github/chatmodes/<name>.chatmode.md          (Copilot, from agents)
    .gemini/commands/claudeflow/<name>.toml        (Gemini CLI, from skills)

Claude-specific bits that are intentionally NOT mirrored:
    - hooks/ and settings.json (harness-executed; no cross-tool equivalent)
    - .claude-plugin/plugin.json (Claude Code plugin manifest)
    - tools: frontmatter (tool namespaces differ per framework)

Run from repo root:
    python3 scripts/generate-adapters.py
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SKILLS_DIR = ROOT / "skills"
AGENTS_DIR = ROOT / "agents"

CURSOR_DIR = ROOT / ".cursor" / "rules"
COPILOT_PROMPTS_DIR = ROOT / ".github" / "prompts"
COPILOT_CHATMODES_DIR = ROOT / ".github" / "chatmodes"
GEMINI_COMMANDS_DIR = ROOT / ".gemini" / "commands" / "claudeflow"

GENERATED_BANNER = (
    "<!-- GENERATED by scripts/generate-adapters.py from {source}. "
    "Do not edit by hand. -->"
)


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Minimal YAML-ish frontmatter parser: flat key: value pairs only."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    head = text[4:end]
    body = text[end + 5 :]
    meta: dict[str, str] = {}
    for line in head.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z0-9_-]+)\s*:\s*(.*)$", line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if (val.startswith('"') and val.endswith('"')) or (
            val.startswith("'") and val.endswith("'")
        ):
            val = val[1:-1]
        meta[key] = val
    return meta, body.lstrip("\n")


def load_skills() -> list[tuple[str, dict[str, str], str]]:
    out = []
    if not SKILLS_DIR.is_dir():
        return out
    for skill_dir in sorted(SKILLS_DIR.iterdir()):
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.is_file():
            continue
        meta, body = parse_frontmatter(skill_md.read_text())
        name = meta.get("name", skill_dir.name)
        out.append((name, meta, body))
    return out


def load_agents() -> list[tuple[str, dict[str, str], str]]:
    out = []
    if not AGENTS_DIR.is_dir():
        return out
    for agent_md in sorted(AGENTS_DIR.glob("*.md")):
        meta, body = parse_frontmatter(agent_md.read_text())
        name = meta.get("name", agent_md.stem)
        out.append((name, meta, body))
    return out


def clean(dir_path: Path) -> None:
    if dir_path.exists():
        shutil.rmtree(dir_path)
    dir_path.mkdir(parents=True, exist_ok=True)


def write_cursor_rule(name: str, description: str, body: str, source: str) -> Path:
    """Cursor rule (.mdc). Uses description-based matching; not always-applied."""
    path = CURSOR_DIR / f"{name}.mdc"
    front = (
        "---\n"
        f"description: {description}\n"
        "alwaysApply: false\n"
        "---\n"
    )
    content = f"{front}\n{GENERATED_BANNER.format(source=source)}\n\n{body}"
    path.write_text(content)
    return path


def write_copilot_prompt(name: str, description: str, body: str, source: str) -> Path:
    """Copilot reusable prompt — invoked via /<name> in Copilot Chat."""
    path = COPILOT_PROMPTS_DIR / f"{name}.prompt.md"
    front = (
        "---\n"
        "mode: agent\n"
        f"description: {description}\n"
        "---\n"
    )
    content = f"{front}\n{GENERATED_BANNER.format(source=source)}\n\n{body}"
    path.write_text(content)
    return path


def write_copilot_chatmode(name: str, description: str, body: str, source: str) -> Path:
    """Copilot custom chat mode — closest analogue to a Claude sub-agent."""
    path = COPILOT_CHATMODES_DIR / f"{name}.chatmode.md"
    front = (
        "---\n"
        f"description: {description}\n"
        "tools: []\n"
        "---\n"
    )
    content = f"{front}\n{GENERATED_BANNER.format(source=source)}\n\n{body}"
    path.write_text(content)
    return path


def toml_escape_triple(s: str) -> str:
    # Triple-quoted TOML strings: escape backslashes and any literal """ sequences.
    return s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def write_gemini_command(name: str, description: str, body: str, source: str) -> Path:
    """Gemini CLI namespaced command — invoked as /claudeflow:<name>."""
    path = GEMINI_COMMANDS_DIR / f"{name}.toml"
    banner = f"# {GENERATED_BANNER.format(source=source)[5:-4].strip()}\n"
    desc_escaped = description.replace("\\", "\\\\").replace('"', '\\"')
    prompt_body = toml_escape_triple(body.rstrip())
    content = (
        f'{banner}'
        f'description = "{desc_escaped}"\n'
        f'prompt = """\n{prompt_body}\n"""\n'
    )
    path.write_text(content)
    return path


def main() -> int:
    skills = load_skills()
    agents = load_agents()

    if not skills and not agents:
        print("No skills or agents found; nothing to generate.", file=sys.stderr)
        return 1

    for d in (CURSOR_DIR, COPILOT_PROMPTS_DIR, COPILOT_CHATMODES_DIR, GEMINI_COMMANDS_DIR):
        clean(d)

    written: list[Path] = []

    for name, meta, body in skills:
        desc = meta.get("description", "")
        src = f"skills/{name}/SKILL.md"
        written.append(write_cursor_rule(name, desc, body, src))
        written.append(write_copilot_prompt(name, desc, body, src))
        written.append(write_gemini_command(name, desc, body, src))

    for name, meta, body in agents:
        desc = meta.get("description", "")
        src = f"agents/{name}.md"
        written.append(write_cursor_rule(name, desc, body, src))
        written.append(write_copilot_chatmode(name, desc, body, src))
        # Gemini sub-agent format is less stable across versions; skip for now.

    print(f"Wrote {len(written)} adapter file(s):")
    for p in written:
        print(f"  {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
